import type { CoalDocument, PipelineStage, StageStatus } from "@/types";

const STAGES = [
  ["upload", "Upload"],
  ["ocr", "OCR / Text Extraction"],
  ["classify", "Document Classification"],
  ["tables", "Table Extraction"],
  ["entities", "Entity Extraction"],
  ["validation", "Validation"],
  ["indexing", "Indexing"],
  ["ready", "Ready for AI Query"],
] as const;

export function buildPipeline(doneUpTo: number, tail: StageStatus = "pending", pages = 0): PipelineStage[] {
  const details: Record<string, string> = {
    upload: "File received and checksum verified",
    ocr: `${pages || "—"} pages parsed`,
    classify: "Classified by content model",
    tables: "Tables detected and normalised",
    entities: "Companies, periods, quantities tagged",
    validation: "Cross-checked with reference datasets",
    indexing: "Chunks embedded for retrieval",
    ready: "Available to AI Assistant",
  };
  return STAGES.map(([key, label], i) => ({
    key,
    label,
    status: i < doneUpTo ? "done" : i === doneUpTo ? tail : "pending",
    detail: details[key],
  }));
}

